export type MessageKey = keyof typeof zh;

export function readLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function writeLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Private mode can reject storage; the toggle still works for this visit.
  }
}

export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const table = lang === "en" ? en : zh;
  const template = table[key as MessageKey] ?? zh[key as MessageKey] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function translateCode(lang: Lang, code: string): string {
  const split = code.indexOf(":");
  if (split === -1) return t(lang, code);
  const value = code.slice(split + 1);
  return t(lang, code.slice(0, split), { n: value, base: value });
}

export function translateWarning(warning: string, lang: Lang): string {
  const square = /Icon is not square \((\d+)x(\d+)\)/i.exec(warning);
  if (square) return t(lang, "warning.square", { width: square[1] ?? "", height: square[2] ?? "" });
  if (/keeping the template placeholder icon/i.test(warning)) return t(lang, "warning.placeholder");
  const guessed = /Dependency "([^"]+)" uses maven\.modrinth; its mod metadata id is guessed as "([^"]+)"/.exec(warning);
  if (guessed) return t(lang, "warning.modrinth", { slug: guessed[1] ?? "", guess: guessed[2] ?? "" });
  if (/hexCastingAddon recipe: could not fetch/i.test(warning)) return t(lang, "warning.hexOffline");
  const compileOnly = /Dependency "([^"]+)" has depType "([^"]+)"/.exec(warning);
  if (compileOnly) {
    const depType = t(lang, `depType.${compileOnly[2] ?? ""}`);
    return t(lang, "warning.compileOnly", { slug: compileOnly[1] ?? "", depType });
  }
  if (/generate timed out/i.test(warning)) return t(lang, "engine.timeout");
  return warning;
}

export function translateEngineError(message: string, lang: Lang = "zh"): string {
  if (/generate timed out/i.test(message)) return t(lang, "engine.timeout");
  if (/modId must match/i.test(message)) return t(lang, "engine.modId");
  if (/modId must be 64/i.test(message)) return t(lang, "engine.modIdLength");
  if (/mavenGroup must be a dotted/i.test(message)) return t(lang, "engine.maven");
  if (/Java keyword/i.test(message)) return t(lang, "engine.keyword");
  if (/displayName must be/i.test(message)) return t(lang, "engine.displayName");
  if (/modVersion must be/i.test(message)) return t(lang, "engine.modVersion");
  if (/kotlin must be/i.test(message)) return t(lang, "engine.kotlin");
  if (/Unknown base|Invalid base/i.test(message)) return t(lang, "engine.base");
  if (/CurseForge is not implemented|source must be "modrinth"/i.test(message)) return t(lang, "engine.curse");
  if (/not a PNG/i.test(message)) return t(lang, "engine.png");
  if (/512KB|icon size limit/i.test(message)) return t(lang, "engine.iconSize");
  if (/icon: provide only one/i.test(message)) return t(lang, "engine.iconOne");
  if (/Modrinth request failed|was not found for project/i.test(message)) return t(lang, "engine.modrinth");
  if (/options must be an object/i.test(message)) return t(lang, "engine.options");
  return t(lang, "engine.generic");
}
