const TEXT_EXTENSIONS = new Set([
  ".kt",
  ".java",
  ".kts",
  ".gradle",
  ".properties",
  ".toml",
  ".json",
  ".json5",
  ".yml",
  ".yaml",
  ".md",
  ".txt",
  ".xml",
  ".cfg",
  ".lang",
  ".mcmeta",
  ".snbt",
  ".jinja",
]);

const SKIP_NAMES = new Set([
  "template.json",
  ".git",
  ".gradle",
  "build",
  "node_modules",
  ".DS_Store",
]);

function isTextPath(path: string): boolean {
  const lower = path.toLowerCase();
  const dot = lower.lastIndexOf(".");
  if (dot === -1) {
    // wrapper scripts etc.
    const base = lower.split(/[\\/]/).pop() ?? "";
    return base === "gradlew" || base === "gradlew.bat" || base === "LICENSE";
  }
  return TEXT_EXTENSIONS.has(lower.slice(dot));
}

async function walkFiles(root: string): Promise<string[]> {
  const out: string[] = [];
  async function walk(dir: string): Promise<void> {
    const entries = await readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      if (SKIP_NAMES.has(entry.name) || entry.name.startsWith(".git")) {
        continue;
      }
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        await walk(full);
      } else if (entry.isFile()) {
        out.push(full);
      }
    }
  }
  await walk(root);
  return out;
}

function shouldKeepFile(relPath: string, kotlin: boolean, recipes: { hexdoc?: boolean }): boolean {
  const norm = relPath.split(sep).join("/");
  if (!kotlin && norm.endsWith(".kt")) {
    return false;
  }
  if (kotlin && norm.includes("/src/main/java/") && norm.endsWith(".java")) {
    return false;
  }
  if (!recipes.hexdoc && (norm === "doc" || norm.startsWith("doc/"))) {
    return false;
  }
  return true;
}

function mergePlans(plans: GradleDepPlan[]): GradleDepPlan {
  const repositories = new Set<string>();
  const common: string[] = [];
  const fabric: string[] = [];
  const forge: string[] = [];
  const neoforge: string[] = [];
  const metadata = [];
  const warnings: string[] = [];
  for (const plan of plans) {
    for (const repo of plan.repositories) repositories.add(repo);
    common.push(...plan.dependencies.common);
    fabric.push(...plan.dependencies.fabric);
    forge.push(...plan.dependencies.forge);
    neoforge.push(...plan.dependencies.neoforge);
    metadata.push(...plan.metadata);
    warnings.push(...plan.warnings);
  }
  return {
    repositories: [...repositories],
    dependencies: { common, fabric, forge, neoforge },
    metadata,
    warnings,
  };
}

function renderDepsSnippet(plan: GradleDepPlan): string {
  const repos = plan.repositories.map((r) => `    ${r.replace(/\n/g, "\n    ")}`).join("\n");
  const lines = (arr: string[]) => arr.map((d) => `    ${d}`).join("\n");
  return `// Generated by arch-template — Modrinth / coord overrides
repositories {
${repos || "    // (none)"}
}

dependencies {
    // common
${lines(plan.dependencies.common) || "    // (none)"}
}

// Platform-specific example lines (merge into fabric/forge/neoforge build files as needed):
// fabric:
${plan.dependencies.fabric.map((d) => `//   ${d}`).join("\n") || "//   (none)"}
// forge:
${plan.dependencies.forge.map((d) => `//   ${d}`).join("\n") || "//   (none)"}
// neoforge:
${plan.dependencies.neoforge.map((d) => `//   ${d}`).join("\n") || "//   (none)"}
`;
}


function formatInjectedLines(lines: string[], indent: string): string {
  if (!lines.length) return "";
  return lines
    .map((line) =>
      line
        .split("\n")
        .map((part) => `${indent}${part}`)
        .join("\n"),
    )
    .join("\n");
}

/**
 * Replace a whole line that contains an __ARCH_TEMPLATE_*__ marker.
 * Indent of the injected block follows the marker line's leading whitespace.
 */
function replaceMarkerLine(text: string, marker: string, lines: string[]): string {
  const re = new RegExp(`^([ \t]*).*${marker}.*$`, "m");
  const match = text.match(re);
  if (!match) {
    return text.split(marker).join(formatInjectedLines(lines, "    "));
  }
  const indent = match[1] ?? "    ";
  const replacement = formatInjectedLines(lines, indent);
  return text.replace(re, replacement === "" ? "" : replacement);
}

/** Replace __ARCH_TEMPLATE_*__ markers in Gradle files with resolved deps/repos. */
function injectDepMarkers(text: string, plan: GradleDepPlan): string {
  let out = text;
  out = replaceMarkerLine(out, "__ARCH_TEMPLATE_REPOS__", plan.repositories);
  out = replaceMarkerLine(out, "__ARCH_TEMPLATE_COMMON_DEPS__", plan.dependencies.common);
  out = replaceMarkerLine(out, "__ARCH_TEMPLATE_FABRIC_DEPS__", plan.dependencies.fabric);
  out = replaceMarkerLine(out, "__ARCH_TEMPLATE_FORGE_DEPS__", plan.dependencies.forge);
  out = replaceMarkerLine(out, "__ARCH_TEMPLATE_NEOFORGE_DEPS__", plan.dependencies.neoforge);
  // Drop leftover blank lines created by empty markers
  out = out.replace(/\n{3,}/g, "\n\n");
  return out;
}

function patchFabricDepends(jsonText: string, plan: GradleDepPlan): string {
  try {
    const data = JSON.parse(jsonText) as { depends?: Record<string, string> };
    data.depends ??= {};
    for (const meta of plan.metadata) {
      if (meta.depType === "required") {
        data.depends[meta.modId] = `>=${meta.versionNumber}`;
      } else if (meta.depType === "optional") {
        data.depends[meta.modId] = `*`;
      }
    }
    return JSON.stringify(data, null, 2) + "\n";
  } catch {
    return jsonText;
  }
}

function patchModsToml(toml: string, plan: GradleDepPlan, modId: string): string {
  let out = toml;
  for (const meta of plan.metadata) {
    out += `
[[dependencies.${modId}]]
modId = "${meta.modId}"
mandatory = ${meta.depType === "required"}
versionRange = "[${meta.versionNumber},)"
ordering = "NONE"
side = "BOTH"
`;
  }
  return out;
}

export async function loadPreset(
  presetId: string,
  presetsRoot?: string,
): Promise<GenerateOptions> {
  const root =
    presetsRoot ??
    resolve(fileURLToPath(new URL("../presets", import.meta.url)));
  const path = resolve(root, `${presetId}.json`);
  const raw = JSON.parse(readFileSync(path, "utf8")) as GenerateOptions;
  return { ...raw, presetId };
}

export async function generateZip(options: GenerateOptions): Promise<GenerateResult> {
  validateOptions(options);
  const warnings: string[] = [];

  const bases = await listBases();
  const baseInfo = await resolveBaseDir(options.base);
  // Soft check against list (resolveBaseDir already throws if missing)
  void bases;

  const recipes = options.recipes ?? {};
  const placeholders = buildPlaceholderMap(options, baseInfo.meta);
  const wrapperUrl = resolveGradleDistributionUrl(options.mirrors?.gradleWrapper);
  placeholders.__GRADLE_DISTRIBUTION_URL__ = escapeGradleDistributionUrl(wrapperUrl);
  const icon = await resolveIconBytes(options.icon);
  warnings.push(...icon.warnings);

  const plans: GradleDepPlan[] = [];
  for (const dep of options.dependencies ?? []) {
    if (dep.source !== "modrinth") {
      throw new Error(`Unsupported dependency source: ${dep.source}`);
    }
    const project = await fetchProject(dep.project);
    const version = await fetchVersion(dep.project, dep.version);
    plans.push(
      buildGradleDeps(project, version, {
        minecraftVersion: baseInfo.meta.minecraft,
        depType: dep.depType,
      }),
    );
  }
  // Optional hex casting addon recipe injects a default dep if not already present
  if (recipes.hexCastingAddon) {
    const hasHex = (options.dependencies ?? []).some((d) =>
      ["hex-casting", "hexcasting"].includes(d.project),
    );
    if (!hasHex) {
      try {
        const project = await fetchProject("hex-casting");
        const version = await fetchVersion("hex-casting", "0.11.4");
        plans.push(
          buildGradleDeps(project, version, {
            minecraftVersion: baseInfo.meta.minecraft,
            depType: "required",
          }),
        );
      } catch (err) {
        warnings.push(
          `hexCastingAddon recipe: could not fetch hex-casting from Modrinth (${String(err)}); emitting coord override lines with version 0.11.4 offline.`,
        );
        plans.push(
          buildGradleDeps(
            { id: "hexcasting", slug: "hex-casting", title: "Hex Casting" },
            {
              id: "offline",
              project_id: "hexcasting",
              version_number: "0.11.4",
            },
            { minecraftVersion: baseInfo.meta.minecraft, depType: "required" },
          ),
        );
      }
    }
  }

  const depPlan = mergePlans(plans);
  warnings.push(...depPlan.warnings);

  const files = await walkFiles(baseInfo.dir);
  const zip = new JSZip();
  const rootPrefix = `${options.modId}/`;

  for (const full of files) {
    let rel = relative(baseInfo.dir, full).split(sep).join("/");
    if (!shouldKeepFile(rel, options.kotlin, recipes)) {
      continue;
    }
    rel = replacePath(rel, placeholders);

    const bytes = await readFile(full);
    if (isTextPath(full)) {
      let text = bytes.toString("utf8");
      text = applyConditionals(text, options.kotlin);
      text = expandPlaceholders(text, placeholders);
      if (rel.endsWith(".gradle") || rel.endsWith(".gradle.kts") || rel.endsWith(".properties")) {
        text = injectDepMarkers(text, depPlan);
      }

      if (rel.endsWith("fabric.mod.json") && depPlan.metadata.length) {
        text = patchFabricDepends(text, {
          ...depPlan,
          metadata: depPlan.metadata.map((m) => ({
            ...m,
            // already expanded mod ids
          })),
        });
        // patchFabricDepends re-stringifies; placeholders in other fields already expanded
      }
      if (
        (rel.endsWith("mods.toml") || rel.endsWith("neoforge.mods.toml")) &&
        depPlan.metadata.length
      ) {
        // deps were appended with __MOD_ID__ before expand — re-expand
        text = patchModsToml(text, depPlan, options.modId);
      }

      zip.file(rootPrefix + rel, text);
    } else {
      zip.file(rootPrefix + rel, bytes);
    }
  }

  // Overlay custom icon onto expected paths
  if (icon.bytes) {
    const iconPaths = [
      `common/src/main/resources/assets/${options.modId}/icon.png`,
      `common/src/main/resources/icon.png`,
    ];
    for (const p of iconPaths) {
      zip.file(rootPrefix + p, icon.bytes);
    }
  }

  if (depPlan.repositories.length || depPlan.dependencies.common.length) {
    zip.file(rootPrefix + "gradle/arch-template-deps.gradle.kts", renderDepsSnippet(depPlan));
  }

  if (options.mirrors?.enabled && options.mirrors.preset === "cn-campus") {
    zip.file(rootPrefix + "gradle/init-mirrors.gradle", buildInitMirrorsGradle());
  }

  // Drop template.json if somehow included
  zip.remove(rootPrefix + "template.json");

  const buffer = Buffer.from(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
  return { buffer, warnings };
}

