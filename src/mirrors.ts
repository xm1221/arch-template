/**
 * Generate an opt-in Gradle init script for CN Maven mirrors.
 *
 * Mirrors are only added for mavenCentral / plugin portal resolution. The
 * script does not rewrite Fabric, Forge, NeoForge, or other exclusive repos.
 */

/** Gradle version shipped in template wrappers. Loom 1.9 requires >= 8.6. */
export const DEFAULT_GRADLE_VERSION = "8.13";

const OFFICIAL_WRAPPER = (version: string) =>
  `https://services.gradle.org/distributions/gradle-${version}-bin.zip`;

/** Tencent Cloud mirror of Gradle distributions. */
const TENCENT_WRAPPER = (version: string) =>
  `https://mirrors.cloud.tencent.com/gradle/gradle-${version}-bin.zip`;

export type GradleWrapperMirror = "official" | "tencent";

export function resolveGradleDistributionUrl(
  mirror: GradleWrapperMirror | undefined,
  gradleVersion: string = DEFAULT_GRADLE_VERSION,
): string {
  if (mirror === "tencent") {
    return TENCENT_WRAPPER(gradleVersion);
  }
  return OFFICIAL_WRAPPER(gradleVersion);
}

/** Escape a URL for gradle-wrapper.properties distributionUrl=... */
export function escapeGradleDistributionUrl(url: string): string {
  return url.replace(/:/g, "\\:");
}

export function buildInitMirrorsGradle(): string {
  return `// Generated by arch-template (CN campus mirror preset).
// Usage: ./gradlew --init-script gradle/init-mirrors.gradle build
// Only Maven Central and the Gradle plugin portal are mirrored. Platform
// exclusive repositories (Fabric/Forge/NeoForge/Modrinth) are left untouched.
def cnMirrors = [
    'https://maven.aliyun.com/repository/public',
    'https://mirrors.cloud.tencent.com/nexus/repository/maven-public/',
    'https://repo.huaweicloud.com/repository/maven/',
    'https://mirrors.bfsu.edu.cn/maven/repository/'
]

def addMirrors = { repos ->
    cnMirrors.eachWithIndex { mirror, index ->
        repos.maven {
            name = "cnMirror\${index}"
            url = uri(mirror)
        }
    }
}

gradle.beforeSettings { settings ->
    addMirrors(settings.pluginManagement.repositories)
}

gradle.allprojects { project ->
    project.repositories {
        addMirrors(delegate)
    }
}
`;
}
